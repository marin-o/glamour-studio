import {
  mkdir,
  readdir,
  readFile,
  stat,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const MEDIA_ROOT = path.resolve("public/media/lookbook/approved");
const MANIFEST_PATH = path.resolve(
  "src/generated/lookbook-media-manifest.js",
);
const RASTER_EXTENSIONS = new Set([".jpeg", ".jpg", ".png", ".webp"]);
const MAX_RASTER_BYTES = 4 * 1024 * 1024;

function publicPath(filePath) {
  return `/${path
    .relative(path.resolve("public"), filePath)
    .replaceAll("\\", "/")}`;
}

async function getMediaFiles() {
  const entries = await readdir(MEDIA_ROOT, { withFileTypes: true });

  return entries
    .filter(
      (entry) =>
        entry.isFile() &&
        RASTER_EXTENSIONS.has(path.extname(entry.name).toLowerCase()),
    )
    .map((entry) => path.join(MEDIA_ROOT, entry.name))
    .sort();
}

async function getManifestContents() {
  const entries = [];

  for (const filePath of await getMediaFiles()) {
    const metadata = await sharp(filePath).metadata();

    if (!metadata.width || !metadata.height) {
      throw new Error(`Missing dimensions for ${publicPath(filePath)}`);
    }

    entries.push(
      `  ${JSON.stringify(publicPath(filePath))}: { width: ${metadata.width}, height: ${metadata.height} },`,
    );
  }

  return `// Generated by scripts/media/lookbook-manifest.mjs. Do not edit manually.
export const lookbookMediaDimensions = {
${entries.join("\n")}
};
`;
}

async function checkMedia() {
  const failures = [];
  const mediaFiles = await getMediaFiles();

  for (const filePath of mediaFiles) {
    const { size } = await stat(filePath);

    if (size > MAX_RASTER_BYTES) {
      failures.push(
        `${publicPath(filePath)} is ${Math.round(size / 1024)}KB (budget ${Math.round(MAX_RASTER_BYTES / 1024)}KB)`,
      );
    }
  }

  const normalizeEol = (text) => text.replaceAll("\r\n", "\n");
  const actualManifest = await readFile(MANIFEST_PATH, "utf8").catch(() => "");
  const expectedManifest = await getManifestContents();

  if (normalizeEol(actualManifest) !== normalizeEol(expectedManifest)) {
    failures.push("src/generated/lookbook-media-manifest.js is out of date");
  }

  if (failures.length > 0) {
    console.error("Lookbook media validation failed:");
    for (const failure of failures) console.error(`- ${failure}`);
    console.error("Run `pnpm media:optimize`, then commit the results.");
    process.exitCode = 1;
    return;
  }

  console.log(`Lookbook media check passed (${mediaFiles.length} files).`);
}

async function optimizeMedia() {
  await mkdir(path.dirname(MANIFEST_PATH), { recursive: true });
  await writeFile(MANIFEST_PATH, await getManifestContents());
  await checkMedia();
  console.log("Prepared lookbook source images for responsive delivery.");
}

if (process.argv.includes("--check")) await checkMedia();
else await optimizeMedia();
